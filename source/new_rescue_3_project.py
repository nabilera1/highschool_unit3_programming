# 6차시 함수 버전에 '자료구조'를 더해 게임을 키웠어요.
#   딕셔너리   단어사전 = {주제: {영단어: 뜻}}   → 주제 고르기, 뜻 힌트
#   딕셔너리   점수 = {'구조': 0, '재출동': 0}   → 결과별 횟수 세기
#   2차원 리스트 난이도표[행][열]                → 난이도마다 [이름, 최소 글자, 최대 글자, 힌트 여부]
#   2차원 리스트 키보드판[행][열]                → 중첩 for 로 키보드 모양 출력
#   2차원 리스트 기록표                          → 출동할 때마다 한 줄씩 append, 마지막에 표로 출력
#
# 전체 흐름
#   main() → 번호선택(주제) → 번호선택(난이도) → 한판진행() → 기록표에 추가 → 다시 출동? → 기록표출력()
#   한판진행() 안에서: 비밀단어생성 → [반복] 게임화면생성 → 알파벳한글자리턴 → 판정
#
# 실행 방법: python new_rescue_3_project.py
# =====================================================================
import random

# 구조 신호 그림 리스트: 틀린 횟수가 곧 인덱스
신호그림 = ['[■■■■■■] 구조 신호 아주 강함',
            '[■■■■■□] 구조 신호 강함',
            '[■■■■□□] 구조 신호 양호',
            '[■■■□□□] 구조 신호 보통',
            '[■■□□□□] 구조 신호 약함 - 서둘러요!',
            '[■□□□□□] 구조 신호 아주 약함 - 마지막 기회!',
            '[□□□□□□] 구조 신호 끊김']
최대틀림 = len(신호그림) - 1                      # 6번 틀리면 신호가 끊김

# 딕셔너리 안의 딕셔너리: 주제 → {영어 단어: 한글 뜻}
단어사전 = {
    '구조·안전': {'help': '도움', 'safe': '안전한', 'rescue': '구조', 'doctor': '의사',
              'nurse': '간호사', 'hospital': '병원', 'emergency': '비상', 'firefighter': '소방관'},
    '마음·우정': {'hope': '희망', 'care': '돌봄', 'smile': '미소', 'thanks': '감사',
              'friend': '친구', 'kindness': '친절', 'together': '함께', 'courage': '용기'},
    '정보': {'list': '리스트', 'loop': '반복', 'input': '입력', 'python': '파이썬',
           'output': '출력', 'variable': '변수', 'function': '함수', 'algorithm': '알고리즘'},
}
# 2차원 리스트: 난이도표[행] = [이름, 최소 글자 수, 최대 글자 수, 뜻 힌트 제공]
난이도표 = [['쉬움', 3, 5, True],
            ['보통', 5, 6, False],
            ['어려움', 7, 20, False]]
# 2차원 리스트: 키보드판 (행 = 키보드 줄, 열 = 글자)
키보드판 = [list('qwertyuiop'),
            list('asdfghjkl'),
            list('zxcvbnm')]


def 구조대게임소개():
    print('*' * 44)
    print(' 영단어 구조대 - 주제와 난이도를 골라 출동하세요')
    print(f' 알파벳 한 글자씩 입력, {최대틀림}번 틀리면 신호가 끊겨요!')
    print('*' * 44)


def 번호선택(안내문, 선택지):
    """선택지(리스트)를 번호와 함께 보여 주고, 올바른 번호가 들어올 때까지 다시 묻는다"""
    for i in range(len(선택지)):
        print(f'  {i + 1}. {선택지[i]}')
    while True:
        text = input(안내문 + ' > ').strip()
        if text.isdecimal() and 1 <= int(text) <= len(선택지):
            return int(text) - 1                 # 인덱스로 돌려준다
        print(f'1~{len(선택지)} 사이의 번호를 입력하세요.')


def 비밀단어생성(주제, 난이도):
    """주제의 단어 중 난이도 글자 수에 맞는 단어를 무작위로 고른다"""
    최소, 최대 = 난이도[1], 난이도[2]          # 난이도 = ['쉬움', 3, 5, True] 같은 한 행
    후보 = []
    for 단어 in 단어사전[주제]:                 # 딕셔너리를 for 로 돌리면 키(영단어)가 하나씩 나온다
        if 최소 <= len(단어) <= 최대:
            후보.append(단어)
    if len(후보) == 0:                           # 맞는 단어가 없으면 전체에서 고른다
        후보 = list(단어사전[주제])
    return random.choice(후보)


def 밑줄단어(비밀단어, 맞춘단어):
    """맞힌 글자는 보여 주고 나머지는 _ 로 바꾼 문자열을 돌려준다"""
    결과 = ''
    for 글자 in 비밀단어:
        if 글자 in 맞춘단어:
            결과 = 결과 + 글자 + ' '
        else:
            결과 = 결과 + '_ '
    return 결과


def 구조대위치(비밀단어, 맞춘단어):
    """맞힌 글자 비율만큼 구조대가 친구에게 다가간 길을 문자열로 돌려준다"""
    맞힌수 = 0
    for 글자 in 비밀단어:
        if 글자 in 맞춘단어:
            맞힌수 += 1
    칸 = 맞힌수 * 10 // len(비밀단어)          # 맞힌 비율을 0~10칸으로 바꾼다 (// : 몫)
    return '구조대 [' + '=' * 칸 + '>' + ' ' * (10 - 칸) + '] 친구'


def 키보드출력(틀린단어, 맞춘단어):
    """2차원 리스트 키보드판을 중첩 반복문으로 출력한다 (맞힘: 대문자, 틀림: ·)"""
    for 행 in range(len(키보드판)):
        print(' ' * 행, end='')                  # 줄마다 한 칸씩 들여쓰기
        for 열 in range(len(키보드판[행])):
            글자 = 키보드판[행][열]            # 2차원 리스트: [행][열] 순서로 꺼낸다
            if 글자 in 맞춘단어:
                print(글자.upper(), end=' ')
            elif 글자 in 틀린단어:
                print('·', end=' ')
            else:
                print(글자, end=' ')
        print()


def 게임화면생성(틀린단어, 맞춘단어, 비밀단어):
    print(신호그림[len(틀린단어)])
    print(구조대위치(비밀단어, 맞춘단어))
    print(f'남은 배터리: {최대틀림 - len(틀린단어)}칸   틀린 글자: {" ".join(틀린단어)}')
    키보드출력(틀린단어, 맞춘단어)
    print('암호: ' + 밑줄단어(비밀단어, 맞춘단어))


def 알파벳한글자리턴(사용한글자):
    """공백 제거·소문자 변환 후, 사용하지 않은 알파벳 한 글자가 들어올 때까지 다시 묻는다"""
    while True:
        guess = input('알파벳 한 글자 > ').strip().lower()
        if len(guess) != 1:
            print('한 글자만 입력해 주세요.')
        elif guess not in 'abcdefghijklmnopqrstuvwxyz':
            print('알파벳(a~z)만 입력해 주세요.')
        elif guess in 사용한글자:
            print('이미 입력한 글자입니다. 다른 글자를 고르세요.')
        else:
            return guess


def 모두맞췄는지(비밀단어, 맞춘단어):
    for 글자 in 비밀단어:
        if 글자 not in 맞춘단어:
            return False
    return True


def 한판진행(주제, 난이도):
    """한 번 출동하고 [비밀단어, 결과, 틀린 횟수]를 돌려준다"""
    비밀단어 = 비밀단어생성(주제, 난이도)
    맞춘단어, 틀린단어 = '', ''
    print(f'\n[SOS] {주제} / {난이도[0]} - {len(비밀단어)}글자 암호가 도착했어요.')
    if 난이도[3]:
        print('뜻 힌트: ' + 단어사전[주제][비밀단어])   # 딕셔너리 안의 딕셔너리: [주제][영단어] → 뜻
    while True:
        게임화면생성(틀린단어, 맞춘단어, 비밀단어)
        guess = 알파벳한글자리턴(틀린단어 + 맞춘단어)
        if guess in 비밀단어:
            맞춘단어 = 맞춘단어 + guess
            if 모두맞췄는지(비밀단어, 맞춘단어):
                print(f'\n구조 성공! 암호는 {비밀단어} ({단어사전[주제][비밀단어]}) - 친구가 무사히 돌아왔어요!')
                return [비밀단어, '구조', len(틀린단어)]
        else:
            틀린단어 = 틀린단어 + guess
            if len(틀린단어) == 최대틀림:
                print(신호그림[최대틀림])
                print(f'\n신호가 끊겼어요. 암호는 {비밀단어} ({단어사전[주제][비밀단어]}) - 다시 출동해요!')
                return [비밀단어, '재출동', len(틀린단어)]


def 기록표출력(기록표):
    """2차원 리스트 기록표를 중첩 반복문으로 표처럼 출력한다"""
    제목줄 = ['출동', '주제', '난이도', '단어', '결과', '틀림']
    for 행 in [제목줄] + 기록표:
        for 칸 in 행:
            print(str(칸).ljust(10), end='')   # ljust(10): 10칸 너비로 왼쪽 정렬 (한글은 2칸 차지해 조금 어긋날 수 있음)
        print()


def 게임재실행():
    return input('다시 출동할까요? (y/n) > ').strip().lower().startswith('y')


def main():
    구조대게임소개()
    점수 = {'구조': 0, '재출동': 0}               # 딕셔너리: 결과별 횟수
    기록표 = []                                  # 2차원 리스트: [[출동, 주제, 난이도, 단어, 결과, 틀림], ...]
    주제목록 = list(단어사전.keys())
    난이도이름 = []                              # 난이도표 각 행의 0번 칸(이름)만 모은다
    for 행 in 난이도표:
        난이도이름.append(행[0])
    while True:
        주제 = 주제목록[번호선택('주제 번호', 주제목록)]
        난이도 = 난이도표[번호선택('난이도 번호', 난이도이름)]
        단어, 결과, 틀림 = 한판진행(주제, 난이도)   # 리스트 [단어, 결과, 틀림]을 세 변수로 나눠 받기
        점수[결과] += 1                          # 결과가 '구조'면 점수['구조']가 1 증가
        기록표.append([len(기록표) + 1, 주제, 난이도[0], 단어, 결과, 틀림])
        if not 게임재실행():
            break
    print('\n===== 구조 출동 기록표 =====')
    기록표출력(기록표)
    print(f'총 {len(기록표)}번 출동  구조: {점수["구조"]}명  재출동: {점수["재출동"]}번')


if __name__ == '__main__':
    main()
