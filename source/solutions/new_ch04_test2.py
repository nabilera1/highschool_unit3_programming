"""4차시 코딩 테스트 2: 구조 출동 시뮬레이션 (도전) - 정답 예시 코드

첫째 줄에 암호, 둘째 줄에 입력할 알파벳들이 한 줄로 주어집니다(중복 없음). 앞에서부터 한 글자씩 게임 규칙대로 처리하여, 모두 맞히면 `구조 성공! 틀린 횟수 n`, 6번 틀리면 `신호 끊김`, 글자를 다 써도 끝나지 않으면 `암호 미완성`을 출력하세요. 게임이 끝나면 남은 글자는 무시합니다.
"""

비밀단어 = input()
입력들 = input()
맞춘단어, 틀린단어 = '', ''
결과 = '암호 미완성'
i = 0
while i < len(입력들):              # 글자가 남아 있는 동안
    guess = 입력들[i]
    i += 1
    if guess in 비밀단어:
        맞춘단어 += guess
        모두맞춤 = True
        for 글자 in 비밀단어:
            if 글자 not in 맞춘단어:
                모두맞춤 = False
        if 모두맞춤:
            결과 = f'구조 성공! 틀린 횟수 {len(틀린단어)}'
            break
    else:
        틀린단어 += guess
        if len(틀린단어) == 6:
            결과 = '신호 끊김'
            break
print(결과)
