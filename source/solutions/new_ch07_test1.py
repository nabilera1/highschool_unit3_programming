"""7차시 코딩 테스트 1: 뜻 힌트 사전 (기본) - 정답 예시 코드

첫째 줄에 n, 다음 n줄에 `영단어 뜻`이 주어집니다. 다음 줄에 m, 다음 m줄에 찾을 영단어가 주어지면 뜻을 출력하고, 사전에 없으면 `단어장에 없어요`를 출력하세요.
"""

뜻사전 = {}
n = int(input())
for _ in range(n):
    단어, 뜻 = input().split()      # 'help 도움' → 'help', '도움'
    뜻사전[단어] = 뜻
m = int(input())
for _ in range(m):
    단어 = input()
    if 단어 in 뜻사전:              # 키가 있는지 먼저 확인
        print(뜻사전[단어])
    else:
        print('단어장에 없어요')
