"""6차시 코딩 테스트 2: 구조대 위치 함수 (도전) - 정답 예시 코드

`구조대위치(비밀단어, 맞춘단어)` 함수를 만드세요. 암호에서 공개된 칸 수를 세어 `칸 = 공개칸 * 10 // 글자 수`를 구한 뒤 `'구조대 [' + '=' * 칸 + '>' + ' ' * (10 - 칸) + '] 친구'`를 돌려줍니다. 첫째 줄에 암호, 둘째 줄에 n, 다음 n줄의 맞춘 글자들마다 결과를 출력하세요. (맞춘 글자가 빈 줄일 수 있음)
"""

def 구조대위치(비밀단어, 맞춘단어):
    공개칸 = 0
    for 글자 in 비밀단어:
        if 글자 in 맞춘단어:
            공개칸 += 1
    칸 = 공개칸 * 10 // len(비밀단어)        # 0 ~ 10
    return '구조대 [' + '=' * 칸 + '>' + ' ' * (10 - 칸) + '] 친구'

비밀단어 = input()
n = int(input())
for _ in range(n):
    print(구조대위치(비밀단어, input()))
