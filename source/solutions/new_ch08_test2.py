"""8차시 코딩 테스트 2: 첫 글자 추천 (도전) - 정답 예시 코드

첫째 줄에 영단어들이 공백으로 구분되어 주어집니다. 가장 많은 단어에 들어 있는 글자를 찾아 `글자 n개 단어 (p%)` 형식으로 출력하세요. 한 단어 안에서 같은 글자는 한 번만 세고, p는 소수 첫째 자리까지, 개수가 같으면 알파벳 순서가 빠른 글자를 고릅니다.
"""

words = input().split()
빈도 = {}
for 단어 in words:
    for 글자 in set(단어):          # 한 단어 안의 중복 제거
        빈도[글자] = 빈도.get(글자, 0) + 1

최고 = ''
for 글자 in sorted(빈도):            # 알파벳 순서로 보면서
    if 최고 == '' or 빈도[글자] > 빈도[최고]:   # 더 클 때만 바꾸므로 같으면 앞 글자 유지
        최고 = 글자
p = 빈도[최고] / len(words) * 100
print(f'{최고} {빈도[최고]}개 단어 ({p:.1f}%)')
