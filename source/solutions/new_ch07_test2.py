"""7차시 코딩 테스트 2: 출동 기록 분석 (도전) - 정답 예시 코드

첫째 줄에 n, 다음 n줄에 `단어 결과 틀린횟수`가 주어집니다(결과는 `구조` 또는 `재출동`). 결과별 횟수를 `구조: a명`, `재출동: b번`으로 출력하고, 구조에 성공한 기록 중 틀린 횟수가 가장 많은 '가장 아슬아슬한 구조'를 `가장 아슬아슬한 구조: 단어 (틀림 k)`로 출력하세요(같으면 먼저 나온 것). 구조 기록이 없으면 `구조 기록 없음`을 출력합니다.
"""

기록표 = []                          # 2차원 리스트
점수 = {'구조': 0, '재출동': 0}       # 딕셔너리
n = int(input())
for _ in range(n):
    단어, 결과, 틀림 = input().split()
    기록표.append([단어, 결과, int(틀림)])
    점수[결과] += 1

print(f'구조: {점수["구조"]}명')
print(f'재출동: {점수["재출동"]}번')

아슬 = None                          # 아직 못 찾음
for 행 in 기록표:
    if 행[1] == '구조':
        if 아슬 is None or 행[2] > 아슬[2]:
            아슬 = 행
if 아슬 is None:
    print('구조 기록 없음')
else:
    print(f'가장 아슬아슬한 구조: {아슬[0]} (틀림 {아슬[2]})')
